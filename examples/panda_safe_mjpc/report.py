"""results/report.md and results/bench.png from results/bench.csv, results/closed_loop_*.json, results/verify.json,
results/projection_study.json."""
import csv, json, sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
R = HERE / "results"
rows = list(csv.DictReader(open(R / "bench.csv")))
for r in rows:
    for k in ("K", "T"): r[k] = int(r[k])
    for k in ("tick_median_ms", "tick_p99_ms", "tick_max_ms", "wall_median_ms", "rollout_ms", "model_ms", "integrate_ms", "project_ms"): r[k] = float(r[k])
def pick(ev, K, T):
    c = [r for r in rows if r["evaluator"] == ev and r["K"] == K and r["T"] == T]; return c[-1] if c else None
def load(p):
    return json.loads((R / p).read_text()) if (R / p).exists() else None
cl = load("closed_loop_mppi.json"); osc = load("closed_loop_osc.json"); ver = load("verify.json"); ps = load("projection_study.json")
vev = load("verify_evaluators.json"); cpu_pieces = load("cpu_pieces.json")
K0, T0 = 256, 100
# evaluator -> (label, colour): the paper's fp64-capable baselines plus frax, the stack the demo is built on
EVS = [("cusadi2", "CusADi2 (ours)", "#2a78d6"), ("frax", "frax + cbfpy (JAX/XLA)", "#eb6834"), ("mjx", "MuJoCo XLA + cbfpy (JAX/XLA)", "#8e44ad"),
       ("cusadi", "CusADi (original, one thread per instance)", "#27ae60"), ("cpu", "CasADi C codegen, CPU 16 threads + transfer", "#7f8c8d")]
LABEL = {e: l for e, l, _ in EVS}
o, f = pick("cusadi2", K0, T0), pick("frax", K0, T0)

L = []
L.append("# Safe MPPI on the Panda: one robot, 256 CBF-filtered rollouts per tick, fp64, 50 Hz\n")
L.append("Generated by `report.py`. RTX 4080 + Ryzen 5800X3D, fp64, one native CUDA MPPI driver, five model evaluators (cusadi2 plans; "
         "frax + cbfpy and MuJoCo XLA + cbfpy as jax.export'ed programs through PJRT; the original CusADi's unrolled kernels of the same "
         "CasADi functions; CasADi's C code generation on the CPU with the GPU <-> CPU transfer of every call), identical sampling, "
         "projection, weighting and plant code. Tick = everything between two control outputs, CUDA events on the driver's stream, "
         "median and p99 over 60 ticks on the model plant; pieces timed alone on the sample buffers. MuJoCo Warp, the paper's fourth "
         "GPU baseline, is fp32-only and has no row for this fp64 study.\n")
L.append(f"## Headline (K = {K0} rollouts, T = {T0} steps = {T0 * 0.02:.1f} s horizon; the plant runs at 50 Hz, budget 20 ms)\n")
L.append("| evaluator | tick median | tick p99 | rollout | model call | integrate call | projection (shared) |")
L.append("|---|---:|---:|---:|---:|---:|---:|")
for ev, name, _ in EVS:
    r = pick(ev, K0, T0)
    if r: L.append(f"| {name} | {r['tick_median_ms']:.2f} ms | {r['tick_p99_ms']:.2f} ms | {r['rollout_ms']:.2f} ms | {r['model_ms']:.3f} ms | {r['integrate_ms']:.3f} ms | {o['project_ms']:.3f} ms |")
L.append("\nThe projection column is the cusadi2 run's measurement of the shared kernel: its cost depends on the data left in the sample "
         "buffers (it exits early when no row is violated), and only the capturable evaluators leave the last rollout step there.")
if o:
    sp = []
    for ev, name, _ in EVS[1:]:
        r = pick(ev, K0, T0)
        if r: sp.append(f"{name}: tick {r['tick_median_ms'] / o['tick_median_ms']:.1f}x, model call {r['model_ms'] / o['model_ms']:.1f}x, integrate call {r['integrate_ms'] / o['integrate_ms']:.1f}x")
    L.append("\nSpeed-up of cusadi2 over " + "; ".join(sp) + ".")
    L.append(f"The model and integrate calls are {100 * (o['model_ms'] + o['integrate_ms']) / (o['model_ms'] + o['integrate_ms'] + o['project_ms']):.0f} % of our rollout step"
             + (f" ({100 * (f['model_ms'] + f['integrate_ms']) / (f['model_ms'] + f['integrate_ms'] + o['project_ms']):.0f} % of frax's)." if f else ".") + "\n")
if cpu_pieces:
    c, ct = cpu_pieces["compute_only"], cpu_pieces["transfer"]
    L.append(f"CPU idealized (the same CasADi C code, 16 threads, no transfer, K = {K0}): model call {c['model_ms']:.3f} ms, integrate call {c['integrate_ms']:.3f} ms, "
             f"T = {T0} rollout {c['rollout_ms']:.1f} ms; with the GPU <-> CPU transfer of every call: {ct['model_ms']:.3f} / {ct['integrate_ms']:.3f} ms, rollout {ct['rollout_ms']:.1f} ms. "
             "The MPPI's sampling, projection, weighting and plant step run on the GPU, so the tick of the CPU row is the transfer variant.\n")
    gate = o["tick_p99_ms"] <= 16.0 and f["tick_median_ms"] >= 30.0
    L.append(f"Pass test fixed in advance (ours p99 <= 16 ms AND frax median >= 30 ms at the same K, T): **{'PASS' if gate else 'FAIL'}** at T = {T0}"
             + (" (it holds up to T = 50, see the sweep; the 2 s horizon was chosen for the video over the 50 Hz budget)." if not gate else "."))

L.append(f"## Horizon sweep (K = {K0}) and sample sweep (T = {T0})\n")
L.append("| evaluator | K | T | tick median | tick p99 | rollout | model | integrate | project |")
L.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
ORDER = {e: i for i, (e, _, _) in enumerate(EVS)}
for r in sorted(rows, key=lambda r: (ORDER.get(r["evaluator"], 9), r["K"] != K0, r["K"], r["T"])):
    L.append(f"| {LABEL.get(r['evaluator'], r['evaluator'])} | {r['K']} | {r['T']} | {r['tick_median_ms']:.2f} | {r['tick_p99_ms']:.2f} | {r['rollout_ms']:.2f} | {r['model_ms']:.3f} | {r['integrate_ms']:.3f} | {r['project_ms']:.3f} |")
L.append("\nAt K <= 256 every rollout is a resident block, so cusadi2's model call costs its level count (207 barriers) and not its "
         "arithmetic; the XLA programs are launch-bound at this batch; the original CusADi's one thread per instance leaves the GPU "
         "nearly empty at 256 instances; the CPU row pays the transfer and synchronisation of every call. All grow linearly with T.\n")

if cl:
    L.append("## Closed loop (MuJoCo, frax's demo scene, 50 Hz, 30 s, reach-around waypoint cycle)\n")
    L.append("| controller | waypoints reached | timed out | time to reach (mean / max) | min h2 | applied-controller tick (median / p99) | frax evaluator, same states |")
    L.append("|---|---:|---:|---:|---:|---:|---:|")
    def ttr(c):
        return f"{c['time_to_reach_mean_s']:.2f} / {c['time_to_reach_max_s']:.2f} s" if c.get("time_to_reach_mean_s") is not None else "-"
    L.append(f"| safe MPPI (cusadi2, K = {cl['K']}, T = {cl['T']}) | {cl['waypoints_reached']} | {cl['waypoints_timed_out']} | {ttr(cl)} | {cl['h_min_all']:.4f} | "
             f"{cl['ours_ms_median']:.2f} / {cl['ours_ms_p99']:.2f} ms | " + (f"{cl['frax_ms_median']:.1f} / {cl['frax_ms_p99']:.1f} ms" if cl.get("frax_ms_median") else "-") + " |")
    if osc:
        L.append(f"| filtered OSC (frax demo controller, qpax) | {osc['waypoints_reached']} | {osc['waypoints_timed_out']} | {ttr(osc)} | {osc['h_min_all']:.4f} | "
                 f"{osc['ctrl_wall_ms_median']:.2f} ms (wall) | - |")
    L.append("\nMinimum barrier per group, safe MPPI: " + ", ".join(f"{g} {v:.4f}" for g, v in cl["h_min"].items()) + ".")
    if osc: L.append("Filtered OSC: " + ", ".join(f"{g} {v:.4f}" for g, v in osc["h_min"].items()) + ".")
    L.append(f"\nSafe MPPI: max joint speed {cl['v_max']:.2f} rad/s, mean effective sample size {cl['ess_mean']:.1f} of {cl['K']}. Video: `closed_loop_mppi.mp4`.\n")

if ps:
    L.append("## The shared projection filter against cbfpy's elastic QP (projection_study.py)\n")
    L.append("20-step rollouts from initially safe random states (h2 > 0.02), PD plans with 0.3 rad knot noise; fraction of rollouts whose "
             "barrier minimum falls below -0.01, and the worst minimum:\n")
    L.append("| filter | rollouts below -0.01 | worst h2 min | instances with a violated row after the filter (random states) |")
    L.append("|---|---:|---:|---:|")
    for k, v in ps.items():
        L.append(f"| {k} | {100 * v['rollout_hmin_frac_below_-0.01']:.1f} % | {v['rollout_hmin_min']:.4f} | {100 * v['kind0_inst_frac']:.1f} % |")
    L.append("")

if vev:
    L.append(f"## Evaluator agreement (verify_evaluators.py, fp64, K = {vev['K']}, T = {vev['T']}, {vev['ticks']} identical ticks)\n")
    L.append("Max relative difference to the cusadi2 run of the applied torque, the recorded rollout trajectories (a T-step chain of model + "
             "projection + integrate for 32 samples), the MPPI weights and the plant state:\n")
    L.append("| evaluator | applied torque | rollout trajectories | weights | plant |")
    L.append("|---|---:|---:|---:|---:|")
    for ev, r in vev["evaluators"].items():
        if "error" in r: L.append(f"| {LABEL.get(ev, ev)} | error: {r['error'][:60]} | | | |")
        else: L.append(f"| {LABEL.get(ev, ev)} | {r['u']:.1e} | {r['traj']:.1e} | {r['w']:.1e} | {r['plant']:.1e} |")
    L.append("")
if ver:
    L.append("## Verification (verify.py, fp64)\n")
    L.append(f"cusadi2 model vs frax + cbfpy: u_nom {ver['model']['u_nom']:.1e}, G {ver['model']['G']:.1e}, h {ver['model']['h']:.1e} relative; "
             f"integrate {ver['integrate']['x1']:.1e}; the projection kernel vs its numpy reference {ver['kernel']['u_vs_numpy']:.1e}. "
             f"Model plan: {ver['casadi']['model']['sx_nodes']} SX nodes; integrate plan: {ver['casadi']['integrate']['sx_nodes']}.\n")

(R / "report.md").write_text("\n".join(L) + "\n")
print("\n".join(L))

# ---- plot ----
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
for ev, name, c in EVS:
    rr = sorted([r for r in rows if r["evaluator"] == ev and r["K"] == K0], key=lambda r: r["T"])
    if rr:
        ax[0].plot([r["T"] for r in rr], [r["tick_median_ms"] for r in rr], "o-", color=c, label=f"{name} (median)")
        ax[0].fill_between([r["T"] for r in rr], [r["tick_median_ms"] for r in rr], [r["tick_p99_ms"] for r in rr], color=c, alpha=0.25)
    rk = sorted([r for r in rows if r["evaluator"] == ev and r["T"] == T0], key=lambda r: r["K"])
    if rk: ax[1].plot([r["K"] for r in rk], [r["tick_median_ms"] for r in rk], "o-", color=c, label=name)
ax[0].axhline(20, color="k", ls="--", lw=0.8); ax[1].axhline(20, color="k", ls="--", lw=0.8)
ax[0].set_xlabel("horizon T (steps of 20 ms)"); ax[0].set_ylabel("ms per control tick"); ax[0].set_title(f"K = {K0} rollouts"); ax[0].legend(fontsize=7); ax[0].grid(alpha=0.3); ax[0].set_yscale("log")
ax[1].set_xlabel("rollouts K"); ax[1].set_xscale("log", base=2); ax[1].set_title(f"T = {T0}"); ax[1].grid(alpha=0.3); ax[1].set_yscale("log")
fig.suptitle("Safe MPPI tick time, one Panda, fp64, identical driver, five model evaluators (dashed: 20 ms budget)", fontsize=11)
fig.tight_layout(); fig.savefig(R / "bench.png", dpi=140); print(R / "bench.png")

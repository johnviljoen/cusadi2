"""The function-independent level-parallel CUDA kernel.

One kernel serves every plan: per-function data (node arrays, slot maps, stage
specs) lives in device arrays the kernel reads; only the scalar type is fixed at
emit time. ``write_kernel_source(path, dtype)`` writes the ``.cu``; compile it
into the consumer alongside ``cusadi2.h``.

Grid is (batch, n_stages), one block per (instance, stage), and every block runs
the full level-parallel evaluation. Plain batch-only evaluation is the
``n_stages == 1``, all-"stage" case. The stage arithmetic lives only in the
input/output loops, never in the per-level compute loop.

Emitted host entry points (declared in cusadi2.h):
    cusadi2_launch(...)              pure launch on a stream, returns cudaPeekAtLastError()
    cusadi2_set_shared_memory(bytes) raise-only dynamic shared-memory cap
"""
import os

_TEMPLATE = r"""// AUTOMATICALLY GENERATED by cusadi2.kernel_template: level-parallel kernel ({dtype}).
//
// Stage modes (per arg): 0=STAGE, 1=SHARED, 2=COUPLED.
//   STAGE   -> leading stride n_stages,        knot s = stage
//   SHARED  -> leading stride 1,               knot s = 0
//   COUPLED -> leading stride n_stages+span,   knot s = stage + offset
// Element index: ((inst * stage_count[arg] + s) * nnz[arg] + elem).
#include <cuda_runtime.h>
#include <math.h>

// CasADi op IDs; must match casadi/core/calculus.hpp exactly
enum CasadiOp {
    OP_ASSIGN=0, OP_ADD, OP_SUB, OP_MUL, OP_DIV, OP_NEG,     // 0-5
    OP_EXP, OP_LOG, OP_POW, OP_CONSTPOW, OP_SQRT, OP_SQ,     // 6-11
    OP_TWICE, OP_SIN, OP_COS, OP_TAN, OP_ASIN, OP_ACOS,      // 12-17
    OP_ATAN,                                                    // 18
    OP_LT, OP_LE, OP_EQ, OP_NE, OP_NOT, OP_AND, OP_OR,       // 19-25
    OP_FLOOR, OP_CEIL, OP_FMOD, OP_FABS, OP_SIGN, OP_COPYSIGN,// 26-31
    OP_IF_ELSE_ZERO, OP_ERF, OP_FMIN, OP_FMAX, OP_INV,        // 32-36
    OP_SINH, OP_COSH, OP_TANH, OP_ASINH, OP_ACOSH, OP_ATANH,  // 37-42
    OP_ATAN2                                                    // 43
};

__EXEC_OP__

#define CUSADI2_KERNEL_PARAMS                                                  \
        const {dtype} * const * __restrict__ inputs,                           \
        {dtype} * const * __restrict__ outputs,                                \
        const int total_instances, const int n_stages,                         \
        const int n_consts,                                                    \
        const int * __restrict__ const_slots,                                  \
        const {dtype} * __restrict__ const_vals,                               \
        const int n_inputs,                                                    \
        const int * __restrict__ input_slots,                                  \
        const int * __restrict__ input_args,                                   \
        const int * __restrict__ input_elems,                                  \
        const int * __restrict__ nnz_in,                                       \
        const int * __restrict__ in_stage_mode,                                \
        const int * __restrict__ in_stage_offset,                              \
        const int * __restrict__ in_stage_count,                               \
        const int n_levels,                                                    \
        const int * __restrict__ level_offsets,                                \
        const int * __restrict__ level_widths,                                 \
        const int * __restrict__ node_ops,                                     \
        const int * __restrict__ node_outs,                                    \
        const int * __restrict__ node_in_a,                                    \
        const int * __restrict__ node_in_b,                                    \
        const int n_outputs,                                                   \
        const int * __restrict__ out_slots,                                    \
        const int * __restrict__ out_args,                                     \
        const int * __restrict__ out_elems,                                    \
        const int * __restrict__ nnz_out,                                      \
        const int * __restrict__ out_stage_mode,                               \
        const int * __restrict__ out_stage_count

__global__ void cusadi2_kernel(CUSADI2_KERNEL_PARAMS) {
    extern __shared__ {dtype} w[];
    const int inst  = blockIdx.x;
    const int stage = blockIdx.y;
    const int tid   = threadIdx.x;
    const int block_sz = blockDim.x;
    if (inst >= total_instances || stage >= n_stages) return;

    for (int i = tid; i < n_consts; i += block_sz)
        w[const_slots[i]] = const_vals[i];

    for (int i = tid; i < n_inputs; i += block_sz) {
        int arg  = input_args[i];
        int s = (in_stage_mode[arg] == 1) ? 0 : (stage + in_stage_offset[arg]);
        long long base = ((long long)inst * in_stage_count[arg] + s) * nnz_in[arg];
        w[input_slots[i]] = inputs[arg][base + input_elems[i]];
    }
    __syncthreads();

    // SSA renaming guarantees no slot is both read and written within a level,
    // so one __syncthreads() per level suffices.
    for (int lev = 0; lev < n_levels; lev++) {
        int offset = level_offsets[lev];
        int width = level_widths[lev];
        for (int idx = tid; idx < width; idx += block_sz) {
            int g = offset + idx;
            w[node_outs[g]] = exec_op(node_ops[g], w[node_in_a[g]], w[node_in_b[g]]);
        }
        __syncthreads();
    }

    for (int i = tid; i < n_outputs; i += block_sz) {
        int arg  = out_args[i];
        int s = (out_stage_mode[arg] == 1) ? 0 : stage;
        long long base = ((long long)inst * out_stage_count[arg] + s) * nnz_out[arg];
        outputs[arg][base + out_elems[i]] = w[out_slots[i]];
    }
}

int cusadi2_launch(
        const {dtype} * const * inputs, {dtype} * const * outputs,
        int total_instances, int n_stages, int block_size, int shared_bytes,
        int n_consts, const int *const_slots, const {dtype} *const_vals,
        int n_inputs, const int *input_slots, const int *input_args, const int *input_elems,
        const int *nnz_in, const int *in_stage_mode, const int *in_stage_offset,
        const int *in_stage_count,
        int n_levels, const int *level_offsets, const int *level_widths,
        const int *node_ops, const int *node_outs, const int *node_in_a, const int *node_in_b,
        int n_outputs, const int *out_slots, const int *out_args, const int *out_elems,
        const int *nnz_out, const int *out_stage_mode, const int *out_stage_count,
        cudaStream_t stream) {
    dim3 grid(total_instances, n_stages);
    cusadi2_kernel<<<grid, block_size, shared_bytes, stream>>>(
        inputs, outputs, total_instances, n_stages,
        n_consts, const_slots, const_vals,
        n_inputs, input_slots, input_args, input_elems, nnz_in,
        in_stage_mode, in_stage_offset, in_stage_count,
        n_levels, level_offsets, level_widths,
        node_ops, node_outs, node_in_a, node_in_b,
        n_outputs, out_slots, out_args, out_elems, nnz_out,
        out_stage_mode, out_stage_count);
    return (int)cudaPeekAtLastError();
}

int cusadi2_set_shared_memory(int shared_bytes) {
    // cusadi2_kernel is ONE symbol shared by every uploaded plan, and
    // cudaFuncAttributeMaxDynamicSharedMemorySize REPLACES the cap (it can lower it
    // below the 48KB default). A later, smaller plan must never shrink the cap under
    // an earlier, larger one, so only ever raise it.
    static int configured = 49152;
    if (shared_bytes <= configured) return 0;
    configured = shared_bytes;
    return (int)cudaFuncSetAttribute(cusadi2_kernel,
                                     cudaFuncAttributeMaxDynamicSharedMemorySize,
                                     shared_bytes);
}
"""


def _render(dtype: str) -> str:
    """Fill {dtype} and build exec_op from the op tables so a float kernel uses
    float intrinsics instead of promoting through double."""
    import casadi as ca
    from cusadi2.ops import OP_EXPR_DOUBLE, OP_EXPR_FLOAT
    names = {getattr(ca, n): n for n in dir(ca) if n.startswith("OP_")}
    exprs = OP_EXPR_FLOAT if dtype == "float" else OP_EXPR_DOUBLE
    zero = "0.f" if dtype == "float" else "0.0"
    cases = "\n".join(
        "        case %s: return %s;" % (names[op], e.replace("{0}", "a").replace("{1}", "b"))
        for op, e in exprs.items())
    exec_op = ("__device__ __forceinline__ %s exec_op(int op, %s a, %s b) {\n"
               "    switch (op) {\n%s\n        default: return %s;\n    }\n}"
               % (dtype, dtype, dtype, cases, zero))
    return _TEMPLATE.replace("{dtype}", dtype).replace("__EXEC_OP__", exec_op)


def write_kernel_source(filepath: str, dtype: str = "double") -> str:
    """Write the kernel .cu for `dtype` ("double" or "float"). The consumer must
    compile cusadi2.h with the matching -DCUSADI2_SCALAR."""
    if dtype not in ("double", "float"):
        raise ValueError(f"dtype must be 'double' or 'float', got {dtype!r}")
    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)
    with open(filepath, "w") as f:
        f.write(_render(dtype))
    return filepath

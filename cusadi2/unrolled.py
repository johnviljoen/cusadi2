"""Original-cusadi-style unrolled kernel for one function.

``write_unrolled_source(fn, path, dtype, n_stages=..., in_mode=..., ...)`` emits
a per-function ``.cu``: CasADi's instruction stream (the plan's serial program,
``dag.extract_serial_program``) as straight-line device code, one statement per
instruction on a thread-major global work vector (``work[thread * sz_w + slot]``),
constants as literals, one thread per (instance, stage). That is the execution
model of the original cusadi, reproduced from the same stream the serial
kernel interprets, so the two differ only in code shape. It exists for that
comparison and is the benchmark's "original cusadi" baseline: it pays a
per-function nvcc compile, the cost cusadi2 was built to avoid.

Instructions are split into ``__noinline__`` device functions of ``chunk``
statements when the stream is longer than one chunk (the original split into
200k-instruction subfiles) to keep nvcc and ptxas tractable.

Emitted symbols (``extern "C"``, NAME = ``fn.name()``, S = the dtype):

    int NAME_unrolled_sz_w();
    int NAME_unrolled_n_stages();
    int NAME_unrolled_launch(const S* const* inputs, S* const* outputs, S* work,
                             int total_instances, int block_size, cudaStream_t stream);

``work`` holds ``total_instances * n_stages * sz_w`` scalars. Argument buffers
are laid out exactly as for a plan written with the same specs (``cusadi2.h``
``Arg::len``); the horizon and stage specs are baked in as constants.
"""
import math
import os

import casadi as ca
from casadi import OP_CONST, OP_INPUT, OP_OUTPUT

from cusadi2.dag import extract_serial_program, stage_count
from cusadi2.ops import OP_EXPR_DOUBLE, OP_EXPR_FLOAT
from cusadi2.plan import _specs


def _literal(v: float, dtype: str) -> str:
    if math.isnan(v):
        return "NAN"
    if math.isinf(v):
        return "INFINITY" if v > 0 else "-INFINITY"
    return repr(float(v)) + ("f" if dtype == "float" else "")


def unrolled_statements(fn: ca.Function, dtype: str, n_stages: int, in_mode, in_offset,
                        in_span) -> list:
    """One C statement per CasADi instruction, on work vector `w`."""
    prog = extract_serial_program(fn)
    exprs = OP_EXPR_FLOAT if dtype == "float" else OP_EXPR_DOUBLE
    nnz_in = [fn.nnz_in(a) for a in range(fn.n_in())]
    nnz_out = [fn.nnz_out(a) for a in range(fn.n_out())]
    stmts = []
    for op, o, a, b in zip(prog.ops, prog.outs, prog.in_a, prog.in_b):
        if op == OP_CONST:
            stmts.append(f"w[{o}] = {_literal(prog.const_vals[a], dtype)};")
        elif op == OP_INPUT:
            count = stage_count(in_mode[a], in_span[a], n_stages)
            s = ("0" if in_mode[a] == "shared" else
                 "stage" if in_offset[a] == 0 else f"(stage + {in_offset[a]})")
            stmts.append(f"w[{o}] = inputs[{a}][((long long)inst * {count} + {s}) * {nnz_in[a]} + {b}];")
        elif op == OP_OUTPUT:
            stmts.append(f"outputs[{a}][((long long)inst * {n_stages} + stage) * {nnz_out[a]} + {b}] = w[{o}];")
        else:
            stmts.append(f"w[{o}] = {exprs[op].replace('{0}', f'w[{a}]').replace('{1}', f'w[{b}]')};")
    return stmts, prog.sz_w


def write_unrolled_source(fn: ca.Function, path: str, dtype: str = "double", n_stages: int = 1,
                          in_mode=None, in_offset=None, in_span=None, chunk: int = 200000) -> str:
    """Write the unrolled kernel for `fn` under the given stage specs to `path`."""
    if dtype not in ("double", "float"):
        raise ValueError(f"dtype must be 'double' or 'float', got {dtype!r}")
    in_mode, in_offset, in_span, _ = _specs(fn, n_stages, in_mode, in_offset, in_span, None)
    stmts, sz_w = unrolled_statements(fn, dtype, n_stages, in_mode, in_offset, in_span)
    name = fn.name()
    parts = [stmts[i:i + chunk] for i in range(0, len(stmts), chunk)] or [[]]
    attr = "__forceinline__" if len(parts) == 1 else "__noinline__"
    sig = f"(const S* const* inputs, S* const* outputs, S* w, const int inst, const int stage)"
    lines = [
        f"// AUTOMATICALLY GENERATED by cusadi2.unrolled: original-cusadi-style unrolled kernel "
        f"for {name} ({dtype}, {len(stmts)} instructions, sz_w={sz_w}, n_stages={n_stages}).",
        "// One thread per (instance, stage), thread-major global work vector, one statement per",
        "// CasADi instruction. Argument layout matches the plan with the same stage specs.",
        "#include <cuda_runtime.h>",
        "#include <math.h>",
        f"typedef {dtype} S;",
        f"enum {{ SZ_W = {sz_w}, N_STAGES = {n_stages} }};",
        "",
    ]
    for k, part in enumerate(parts):
        lines.append(f"static __device__ {attr} void {name}_p{k:02d}{sig} {{")
        lines += ["    " + s for s in part]
        lines.append("}")
        lines.append("")
    lines += [
        f"__global__ void {name}_unrolled_kernel(const S* const* inputs, S* const* outputs, S* work,",
        "                                       const long long n_items) {",
        "    const long long g = (long long)blockIdx.x * blockDim.x + threadIdx.x;",
        "    if (g >= n_items) return;",
        "    const int inst = (int)(g / N_STAGES), stage = (int)(g % N_STAGES);",
        "    S* w = work + g * SZ_W;      // thread-major, as in the original cusadi",
    ] + [f"    {name}_p{k:02d}(inputs, outputs, w, inst, stage);" for k in range(len(parts))] + [
        "}",
        "",
        f'extern "C" int {name}_unrolled_sz_w() {{ return SZ_W; }}',
        f'extern "C" int {name}_unrolled_n_stages() {{ return N_STAGES; }}',
        f'extern "C" int {name}_unrolled_launch(const S* const* inputs, S* const* outputs, S* work,',
        "                                      int total_instances, int block_size, cudaStream_t stream) {",
        "    const long long n_items = (long long)total_instances * N_STAGES;",
        f"    {name}_unrolled_kernel<<<(unsigned)((n_items + block_size - 1) / block_size), block_size, 0, stream>>>(",
        "        inputs, outputs, work, n_items);",
        "    return (int)cudaPeekAtLastError();",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path
